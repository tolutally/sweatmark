// Writes a compact copy of the app's exercise library for AI workers.
// Run after the app catalog changes: npm run build:ai-catalog
const fs = require("fs");
const path = require("path");

const source = path.join(__dirname, "..", "..", "assets", "exercises", "catalog_v1.json");
const target = path.join(__dirname, "..", "src", "ai", "catalog.ts");
const {exercises, release} = JSON.parse(fs.readFileSync(source, "utf8"));
const rows = exercises
  .map((e) => [e.id, e.name, e.muscleGroup || "", e.equipment || ""])
  .sort((a, b) => a[0].localeCompare(b[0]));
fs.writeFileSync(target, `// Generated by scripts/build-ai-catalog.js from assets/exercises/catalog_v1.json.
// Do not edit by hand.
export const CATALOG_RELEASE = ${JSON.stringify(release ?? "")};
export const CATALOG: ReadonlyArray<readonly [id: string, name: string, muscle: string, equipment: string]> = ${JSON.stringify(rows)};
`);
console.log(`Wrote ${rows.length} exercises to ${path.relative(process.cwd(), target)}`);
